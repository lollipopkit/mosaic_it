#!/usr/bin/env bash
# Auto-generate the next release version from git commit count (ServerBox style):
#   version = 1.0.<build>+<build>, tag = v1.0.<build>
#
# By default, uses `$(git rev-list --count HEAD) + 1` so that committing this
# bump (or squash-merging it into main) lands with commit count == <build>.
#
# Usage:
#   app/tool/bump-version.sh              # next commit count (HEAD + 1)
#   app/tool/bump-version.sh --current    # exact current HEAD commit count
#   app/tool/bump-version.sh --build 42   # explicit build number
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
APP_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_ROOT="$(cd "$APP_DIR/.." && pwd)"

BUILD=""
USE_CURRENT=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    --current) USE_CURRENT=true; shift ;;
    --build)
      [[ $# -ge 2 ]] || { echo "missing value for --build" >&2; exit 2; }
      BUILD="$2"
      shift 2
      ;;
    -h|--help)
      sed -n '2,12p' "$0"
      exit 0
      ;;
    *)
      echo "unknown option: $1" >&2
      exit 2
      ;;
  esac
done

if [[ -z "$BUILD" ]]; then
  count="$(git -C "$REPO_ROOT" rev-list --count HEAD)"
  if [[ "$USE_CURRENT" == true ]]; then
    BUILD="$count"
  else
    BUILD="$((count + 1))"
  fi
fi

if ! [[ "$BUILD" =~ ^[1-9][0-9]*$ ]]; then
  echo "invalid build number: $BUILD" >&2
  exit 1
fi

VERSION="1.0.${BUILD}"

mkdir -p "$APP_DIR/lib/data/res"
cat > "$APP_DIR/lib/data/res/build_data.dart" <<EOF
// Generated by app/tool/bump-version.sh. Do not edit manually.
// ignore_for_file: prefer_single_quotes

abstract class BuildData {
  static const String name = "MosaicIt";
  static const int build = ${BUILD};
}
EOF

python3 - "$APP_DIR/pubspec.yaml" "$REPO_ROOT/Cargo.toml" "$VERSION" "$BUILD" <<'PY'
import pathlib, re, sys

pubspec_path = pathlib.Path(sys.argv[1])
cargo_path = pathlib.Path(sys.argv[2])
version = sys.argv[3]
build = sys.argv[4]

pub = pubspec_path.read_text(encoding="utf-8")
pub_new, n_pub = re.subn(
    r"^version:\s*[^\r\n]+$",
    f"version: {version}+{build}",
    pub,
    count=1,
    flags=re.M,
)
if n_pub != 1:
    sys.exit(f"Could not update version in {pubspec_path}")
pubspec_path.write_text(pub_new, encoding="utf-8")

cargo = cargo_path.read_text(encoding="utf-8")
cargo_new, n_cargo = re.subn(
    r"(\[workspace\.package\][^\[]*?^version\s*=\s*\")[^\"]+(\")",
    rf"\g<1>{version}\g<2>",
    cargo,
    count=1,
    flags=re.M | re.S,
)
if n_cargo != 1:
    sys.exit(f"Could not update [workspace.package] version in {cargo_path}")
cargo_path.write_text(cargo_new, encoding="utf-8")
PY

if command -v cargo >/dev/null 2>&1; then
  cargo metadata --manifest-path "$REPO_ROOT/Cargo.toml" --format-version 1 --offline >/dev/null 2>&1 \
    || cargo metadata --manifest-path "$REPO_ROOT/Cargo.toml" --format-version 1 >/dev/null
fi

echo "Updated version to ${VERSION}+${BUILD} (tag: v${VERSION})"
